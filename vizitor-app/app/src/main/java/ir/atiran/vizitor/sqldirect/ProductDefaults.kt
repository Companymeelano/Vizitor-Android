package ir.atiran.vizitor.sqldirect

object ProductDefaults {

    /** اگر نام کالا در هیچ دسته‌ای نیفتاد، این حاشیه استفاده می‌شود. */
    const val FALLBACK_MARKUP = 0.20

    /**
     * قواعد نام → دسته + حاشیهٔ پیش‌فرض مصرف‌کننده.
     * ترتیب مهم است: خاص‌ها قبل از عام‌ها.
     */
    private val rules: List<Triple<List<String>, String, Double>> = listOf(
        Triple(
            listOf("پسته", "بادام هندی", "چلغوز", "بادام درشت"),
            "آجیل سخت", 0.18
        ),
        Triple(
            listOf("بادام", "گردو", "فندق", "نخودچی", "آجیل", "مغز"),
            "آجیل و مغزها", 0.20
        ),
        Triple(
            listOf("کشمش", "مویز", "خرما", "انجیر", "برگه", "آلو", "توت", "قیسی", "خرمالو", "خشکبار"),
            "خشکبار", 0.22
        ),
        Triple(
            listOf("تخمه", "آفتابگردان", "کدو", "شاهدانه", "هندوانه", "ژاپنی"),
            "تخمه‌جات", 0.25
        ),
        Triple(
            listOf("زعفران", "هل", "دارچین", "زردچوبه", "فلفل", "ادویه", "زنجبیل", "سماق", "گل پر"),
            "ادویه", 0.30
        ),
        Triple(
            listOf("عسل", "شیره", "ارده", "حلوا", "کره", "سرکه", "ترشی"),
            "خواروبار", 0.25
        ),
        Triple(
            listOf("شکلات", "آبنبات", "پاستیل", "بیسکویت", "کیک", "تنقلات"),
            "تنقلات", 0.28
        ),
        Triple(
            listOf("نوشابه", "آبمیوه", "شربت", "چای", "قهوه", "دمنوش"),
            "نوشیدنی", 0.20
        ),
    )

    /** نام دستهٔ پیشنهادی بر اساس نام کالا (برای نمایش و گروه‌بندی). */
    fun categoryOf(name: String): String {
        val n = name.trim()
        if (n.isBlank()) return "سایر"
        rules.forEach { (keys, category, _) ->
            if (keys.any { n.contains(it, ignoreCase = true) }) return category
        }
        return "سایر"
    }

    /** درصد حاشیهٔ پیش‌فرض مصرف‌کننده بر اساس نام کالا. */
    fun markupFor(name: String): Double {
        val n = name.trim()
        rules.forEach { (keys, _, markup) ->
            if (keys.any { n.contains(it, ignoreCase = true) }) return markup
        }
        return FALLBACK_MARKUP
    }

    /**
     * قیمت مصرف‌کنندهٔ پیش‌فرض از روی قیمت پایه (قیمت فروش) و نام کالا.
     * اگر پایه صفر باشد، صفر برمی‌گردد (هیچ قیمت ساختگی‌ای ساخته نمی‌شود).
     */
    fun consumerFromName(base: Long, name: String): Long {
        if (base <= 0L) return 0L
        val markup = markupFor(name)
        return base + (base * markup).toLong()
    }

    /** درصد حاشیه به‌صورت عدد صحیح برای نمایش: ۲۰ ⇒ ٪۲۰ */
    fun markupPercentFor(name: String): Int = (markupFor(name) * 100).toInt()

    /**
     * قیمت میانگین هر قلم = میانگین سطح‌های غیرصفر قیمت (قیمت واقعی سرور).
     * اگر همه صفر باشند، صفر برمی‌گردد.
     */
    fun averageOf(tiers: List<Long>): Long {
        val live = tiers.filter { it > 0L }
        if (live.isEmpty()) return 0L
        return live.sum() / live.size
    }

    /** میانگین بین کمینه و بیشینه (وقتی سطح‌های قیمتی خالی‌اند ولی Min/Max هست). */
    fun midOf(min: Long, max: Long): Long =
        if (min > 0L && max > 0L) (min + max) / 2 else 0L
}
